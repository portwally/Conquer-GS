#!/usr/bin/env python3
"""Evaluate every `name equ value` in Merlin 32 sources (the order given,
names defined later are resolved too) and print them as a Lua table, for
the MAME test scripts: build/equates.lua, read by tools/vars.lua.
Merlin evaluates expressions strictly left to right; {} groups."""
import re
import sys

EQU = re.compile(r'^([A-Za-z_][A-Za-z0-9_]*)\s+equ\s+(\S+)', re.IGNORECASE)


def tokens(expr):
    i = 0
    while i < len(expr):
        c = expr[i]
        if c == '$':
            m = re.match(r'\$[0-9A-Fa-f]+', expr[i:])
            yield ('num', int(m.group()[1:], 16)); i += len(m.group())
        elif c == '%':
            m = re.match(r'%[01]+', expr[i:])
            yield ('num', int(m.group()[1:], 2)); i += len(m.group())
        elif c.isdigit():
            m = re.match(r'\d+', expr[i:])
            yield ('num', int(m.group())); i += len(m.group())
        elif c.isalpha() or c == '_':
            m = re.match(r'[A-Za-z_][A-Za-z0-9_]*', expr[i:])
            yield ('name', m.group()); i += len(m.group())
        elif c in "'\"":
            yield ('num', ord(expr[i + 1]) | (0x80 if c == '"' else 0)); i += 3
        else:
            yield ('op', c); i += 1


def evaluate(expr, known):
    toks = list(tokens(expr))
    pos = 0

    def term():
        nonlocal pos
        kind, v = toks[pos]; pos += 1
        if kind == 'num':
            return v
        if kind == 'name':
            return known[v]                     # KeyError: not known yet
        if v == '{':
            r = run()
            pos += 1                            # '}'
            return r
        if v == '-':
            return -term()
        raise ValueError(expr)

    def run():
        nonlocal pos
        acc = term()
        while pos < len(toks) and toks[pos] != ('op', '}'):
            _, op = toks[pos]; pos += 1
            b = term()
            acc = {'+': acc + b, '-': acc - b, '*': acc * b, '/': acc // b if b else 0,
                   '&': acc & b, '.': acc | b, '!': acc ^ b}[op]
        return acc

    return run() & 0xFFFFFFFF


def labels(path):
    """Global labels from Merlin 32's symbol file (bank/address;name)."""
    out = {}
    for line in open(path):
        f = line.strip().split(';')
        if len(f) > 6 and '/' in f[4] and not f[5].startswith(':'):
            bank, addr = f[4].split('/')
            out[f[5]] = int(bank, 16) << 16 | int(addr, 16)
    return out


def main(paths):
    known = {}
    if paths and paths[0] == '--symbols':       # equates built on labels
        known = labels(paths[1])
        paths = paths[2:]
    pending = []
    for path in paths:
        for line in open(path):
            m = EQU.match(line)
            if m:
                pending.append((m.group(1), m.group(2)))
    labelnames = set(known)
    while pending:
        left = []
        for name, expr in pending:
            try:
                known[name] = evaluate(expr, known)
            except KeyError:
                left.append((name, expr))
        if len(left) == len(pending):
            raise SystemExit('cannot evaluate: %s' % left)
        pending = left
    print('-- generated by tools/equates.py from %s' % ' '.join(paths))
    print('return {')
    for name, v in known.items():
        if name not in labelnames:
            print('  %s = %d,' % (name, v))
    print('}')


if __name__ == '__main__':
    main(sys.argv[1:])
